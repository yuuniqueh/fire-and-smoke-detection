"""Event review as three distinct user tasks, with a responsive detail area."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QWidget, QFrame, QVBoxLayout, QHBoxLayout, QLabel, QLineEdit,
    QComboBox, QPushButton, QTextEdit, QScrollArea, QSplitter, QMenu, QToolButton, QTabBar)
from ui.widgets import VideoView
from ui.review_controls import fill_conclusions, StatusDelegate


def build_event_page(w, table):
    page = w.event_page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(16)
    filters = QFrame()
    filters.setObjectName('filterBar')
    bar = QHBoxLayout(filters)
    bar.setContentsMargins(14, 12, 14, 12)
    bar.setSpacing(10)
    w.event_query = QLineEdit()
    w.event_query.setPlaceholderText('搜索事件或时间')
    w.event_query.setMinimumWidth(100)
    w.event_query.textChanged.connect(w.filter_events)
    w.event_class, w.event_level, w.event_handling = QComboBox(), QComboBox(), QComboBox()
    for label, value in [('全部类别', ''), ('火焰', 'fire'), ('烟雾', 'smoke')]:
        w.event_class.addItem(label, value)
    for label, value in [('全部等级', ''), ('请核查', 'LOW'), ('优先核查', 'MEDIUM'), ('立即核查', 'HIGH')]:
        w.event_level.addItem(label, value)
    for label, value in [('全部状态', ''), ('待核查', 'review'), ('待处理', 'action'), ('已处理', 'completed'),
            ('全部待办', 'pending'), ('已查看', 'acknowledged'), ('识别误报', 'false_positive'),
            ('继续核查', 'needs_verification'), ('继续核查', 'uncertain'), ('正常用火', 'normal_use'),
            ('确认异常', 'confirmed_abnormal'), ('已处理', 'resolved'), ('无提示记录', 'unavailable')]:
        w.event_handling.addItem(label, value)
    for index in range(4, w.event_handling.count()):
        w.event_handling.view().setRowHidden(index, True)
        w.event_handling.model().item(index).setEnabled(False)
    bar.addWidget(w.event_query, 1)
    for combo, width in ((w.event_class, 122), (w.event_level, 138), (w.event_handling, 165)):
        combo.setMinimumContentsLength(5)
        combo.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        combo.setFixedWidth(width)
        combo.currentIndexChanged.connect(w.filter_events)
        bar.addWidget(combo)
    back = QPushButton('返回事件列表')
    back.setObjectName('quiet')
    back.clicked.connect(lambda: w.navigate('event_board'))
    layout.addWidget(back, 0, Qt.AlignmentFlag.AlignLeft)
    layout.addWidget(filters)

    w.event_split = QSplitter(Qt.Orientation.Horizontal)
    w.event_split.setChildrenCollapsible(False)
    list_card = QFrame()
    list_card.setObjectName('panel')
    list_card.setMinimumWidth(260)
    listing = QVBoxLayout(list_card)
    listing.setContentsMargins(12, 16, 12, 12)
    heading = QHBoxLayout()
    title = QLabel('事件列表')
    title.setObjectName('sectionTitle')
    heading.addWidget(title)
    heading.addStretch()
    w.event_list_count = QLabel('0 条')
    w.event_list_count.setObjectName('statusBadge')
    heading.addWidget(w.event_list_count)
    listing.addLayout(heading)
    w.event_table = table(['事件', '事件 / 等级', '时间', '检测状态', '优先度', '视觉指数', '状态'])
    for column in (0, 3, 4, 5):
        w.event_table.setColumnHidden(column, True)
    w.event_table.setMinimumWidth(228)
    w.event_table.setShowGrid(False)
    w.event_table.setAlternatingRowColors(False)
    w.event_table.itemSelectionChanged.connect(w.select_event)
    w.event_table.setItemDelegateForColumn(6, StatusDelegate(w.event_table))
    w.event_table.doubleClicked.connect(lambda index: w.replay_event())
    listing.addWidget(w.event_table, 1)
    w.event_split.addWidget(list_card)
    w.event_detail_split = QSplitter(Qt.Orientation.Horizontal)
    w.event_detail_split.setChildrenCollapsible(False)

    evidence_card = QFrame()
    evidence_card.setObjectName('panel')
    evidence = QVBoxLayout(evidence_card)
    evidence.setContentsMargins(18, 18, 18, 18)
    evidence.setSpacing(14)
    header = QHBoxLayout()
    w.event_subject = QLabel('现场画面')
    w.event_subject.setObjectName('sectionTitle')
    w.event_subject.setWordWrap(True)
    header.addWidget(w.event_subject, 1)
    w.review_context = QLabel('等待选择')
    w.review_context.setObjectName('statusBadge')
    header.addWidget(w.review_context)
    evidence.addLayout(header)
    w.review_video = VideoView()
    w.review_video.setMinimumSize(160, 180)
    w.review_video.clear_frame('选择事件，查看现场画面')
    evidence.addWidget(w.review_video, 1)
    w.replay_host = QWidget()
    w.replay_host_layout = QVBoxLayout(w.replay_host)
    w.replay_host_layout.setContentsMargins(0, 0, 0, 0)
    w.replay_host.hide()
    evidence.addWidget(w.replay_host, 1)
    w.event_scene = QLabel()
    w.event_scene.setTextFormat(Qt.TextFormat.PlainText)
    w.event_scene.setWordWrap(True)
    w.event_scene.setStyleSheet('background:#eef4ff;border:1px solid #ccdafa;border-radius:10px;padding:14px;font-size:17px;')
    w.event_scene.hide()
    evidence.addWidget(w.event_scene)
    actions = QHBoxLayout()
    w.event_replay = QPushButton('回看片段')
    w.event_replay.setObjectName('primary')
    w.event_replay.clicked.connect(w.replay_event)
    w.event_image = QPushButton('截图')
    w.event_image.clicked.connect(w.close_inline_replay)
    w.event_notice = QPushButton('提示历史')
    w.event_notice.clicked.connect(w.open_event_notification)
    w.event_notice.hide()
    w.event_analysis_button = QPushButton('分析依据')
    w.event_analysis_button.clicked.connect(w.open_event_analysis)
    w.event_analysis_button.hide()
    w.event_details_toggle = QPushButton('详细信息')
    w.event_details_toggle.setCheckable(True)
    w.event_details_toggle.hide()
    more = QToolButton()
    more.setText('更多')
    more.setPopupMode(QToolButton.ToolButtonPopupMode.InstantPopup)
    menu = QMenu(more)
    menu.addAction('提示历史', w.event_notice.click)
    menu.addAction('分析依据', w.event_analysis_button.click)
    detail_action = menu.addAction('详细信息')
    detail_action.setCheckable(True)
    detail_action.toggled.connect(w.event_details_toggle.setChecked)
    more.setMenu(menu)
    actions.addWidget(w.event_replay, 1)
    actions.addWidget(w.event_image)
    actions.addWidget(more)
    evidence.addLayout(actions)
    w.detail = QTextEdit()
    w.detail.setReadOnly(True)
    w.detail.setMaximumHeight(190)
    w.detail.hide()
    w.event_details_toggle.toggled.connect(w.detail.setVisible)
    evidence.addWidget(w.detail)
    w.evidence_scroll = QScrollArea()
    w.evidence_scroll.setWidgetResizable(True)
    w.evidence_scroll.setMinimumWidth(300)
    w.evidence_scroll.setMinimumHeight(200)
    w.evidence_scroll.setWidget(evidence_card)
    w.event_detail_split.addWidget(w.evidence_scroll)

    review_card = QFrame()
    review_card.setObjectName('reviewPanel')
    review_card.setMinimumWidth(270)
    review = QVBoxLayout(review_card)
    review.setContentsMargins(20, 20, 20, 20)
    review.setSpacing(14)
    title = QLabel('核查与处理')
    title.setObjectName('sectionTitle')
    review.addWidget(title)
    w.review_state = QLabel('尚未选择事件')
    w.review_state.setWordWrap(True)
    w.review_state.setObjectName('statusBadge')
    review.addWidget(w.review_state)
    w.review_priority = QLabel()
    w.review_priority.setWordWrap(True)
    review.addWidget(w.review_priority)
    w.review_conclusion = QLabel()
    w.review_conclusion.setWordWrap(True)
    review.addWidget(w.review_conclusion)
    w.review_basis = QLabel('请结合原画面判断。')
    w.review_basis.setWordWrap(True)
    w.review_basis.hide()
    review.addWidget(QLabel('核查结果'))
    w.review_choice = QComboBox()
    fill_conclusions(w.review_choice)
    review.addWidget(w.review_choice)
    w.review_note_toggle = QPushButton('添加备注')
    w.review_note_toggle.setCheckable(True)
    w.review_note_toggle.setObjectName('quiet')
    review.addWidget(w.review_note_toggle, 0, Qt.AlignmentFlag.AlignLeft)
    w.review_comment = QTextEdit()
    w.review_comment.setPlaceholderText('补充观察或处理情况')
    w.review_comment.setMaximumHeight(120)
    w.review_comment.hide()
    w.review_comment.setToolTip('备注最多1000字')
    w.review_note_toggle.toggled.connect(w.review_comment.setVisible)
    review.addWidget(w.review_comment)
    w.review_save = QPushButton('保存核查结果')
    w.review_save.setObjectName('primary')
    w.review_save.clicked.connect(w.save_event_review)
    review.addWidget(w.review_save)
    w.review_resolve = QPushButton('标记已处理')
    w.review_resolve.setObjectName('primary')
    w.review_resolve.clicked.connect(w.complete_event_review)
    w.review_resolve.hide()
    review.addWidget(w.review_resolve)
    w.review_reopen = QPushButton('撤回处理')
    w.review_reopen.setObjectName('quiet')
    w.review_reopen.setStyleSheet('QPushButton {background:#fff7e9;color:#925610;border:1px solid #dfbd83;border-radius:12px;padding:10px 14px;font-size:16px;} QPushButton:hover {background:#ffedcd;}')
    w.review_reopen.setToolTip('撤回后重新跟进，原核查与处理记录继续保留。')
    w.review_reopen.clicked.connect(w.reopen_event_review)
    w.review_reopen.hide()
    review.addWidget(w.review_reopen)
    w.review_ack = QPushButton('标记已查看')
    w.review_ack.setToolTip('记录已阅读，事件仍需核查。')
    w.review_ack.clicked.connect(w.acknowledge_selected_event)
    review.addWidget(w.review_ack)
    history = QPushButton('查看处理记录')
    history.clicked.connect(w.show_event_review_history)
    review.addWidget(history)
    w.completed_events_button = QPushButton('查看已处理事件')
    w.completed_events_button.clicked.connect(w.show_completed_events)
    w.completed_events_button.hide()
    review.addWidget(w.completed_events_button)
    w.review_save_status = QLabel('')
    w.review_save_status.setWordWrap(True)
    w.review_save_status.setObjectName('muted')
    review.addWidget(w.review_save_status)
    review.addStretch()
    w.review_scroll = QScrollArea()
    w.review_scroll.setWidgetResizable(True)
    w.review_scroll.setMinimumWidth(285)
    w.review_scroll.setMinimumHeight(170)
    w.review_scroll.setWidget(review_card)
    w.event_detail_split.addWidget(w.review_scroll)
    w.event_detail_split.setSizes([560, 330])
    w.event_detail_split.setStretchFactor(0, 2)
    detail_host = QWidget()
    detail_layout = QVBoxLayout(detail_host)
    detail_layout.setContentsMargins(0, 0, 0, 0)
    detail_layout.setSpacing(10)
    w.event_detail_tabs = QTabBar()
    w.event_detail_tabs.addTab('现场画面')
    w.event_detail_tabs.addTab('核查处理')
    w.event_detail_tabs.setExpanding(True)
    w.event_detail_tabs.hide()
    w.event_detail_tabs.currentChanged.connect(lambda _: w._adapt_event_layout())
    detail_layout.addWidget(w.event_detail_tabs)
    detail_layout.addWidget(w.event_detail_split, 1)
    w.event_split.addWidget(detail_host)
    w.event_split.setSizes([300, 890])
    w.event_split.setStretchFactor(1, 3)
    layout.addWidget(w.event_split, 1)
    w.event_count = QLabel()
    w.event_count.hide()
    w.tabs.addTab(page, '事件核查')
