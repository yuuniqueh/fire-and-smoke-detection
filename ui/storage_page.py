"""Storage overview with clear totals and on-demand retention controls."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QWidget, QFrame, QVBoxLayout, QHBoxLayout, QGridLayout,
    QLabel, QPushButton, QComboBox, QSpinBox, QCheckBox, QMessageBox)


def storage_size(value):
    if value >= 1024 ** 3:
        return f'{value / 1024 ** 3:.2f} GB'
    return f'{value / 1024 ** 2:.1f} MB'


def build_storage_page(w, table):
    page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(16)
    metrics = QHBoxLayout()
    metrics.setSpacing(16)
    w.storage_metrics = {}
    for key, caption in (('used', '已用空间'), ('reclaim', '可清理空间'), ('count', '保存记录')):
        card = QFrame()
        card.setObjectName('panel')
        cell = QVBoxLayout(card)
        cell.setContentsMargins(20, 16, 20, 16)
        label = QLabel(caption)
        label.setObjectName('metricCaption')
        cell.addWidget(label)
        value = QLabel('—')
        value.setObjectName('metricValue')
        cell.addWidget(value)
        w.storage_metrics[key] = value
        metrics.addWidget(card, 1)
    layout.addLayout(metrics)
    policy = QFrame()
    policy.setObjectName('panel')
    policy_layout = QVBoxLayout(policy)
    policy_layout.setContentsMargins(18, 14, 18, 14)
    heading = QHBoxLayout()
    title = QLabel('录制与保留设置')
    title.setObjectName('sectionTitle')
    heading.addWidget(title, 1)
    w.storage_policy_toggle = QPushButton('展开设置')
    w.storage_policy_toggle.setCheckable(True)
    heading.addWidget(w.storage_policy_toggle)
    policy_layout.addLayout(heading)
    w.storage_policy_body = QWidget()
    form = QGridLayout(w.storage_policy_body)
    form.setContentsMargins(0, 16, 0, 2)
    form.setHorizontalSpacing(18)
    form.setVerticalSpacing(16)
    w.recording_mode = QComboBox()
    for caption, value in [('保存事件片段', 'events'), ('保存完整录像', 'full'), ('仅保存截图与记录', 'none')]:
        w.recording_mode.addItem(caption, value)
    w.storage_max_gb = QSpinBox()
    w.storage_max_gb.setRange(1, 1000)
    w.storage_max_gb.setSuffix(' GB')
    w.storage_days = QSpinBox()
    w.storage_days.setRange(1, 3650)
    w.storage_days.setSuffix(' 天')
    w.storage_automatic = QCheckBox('自动清理过期或超额记录')
    w.storage_automatic.setToolTip('会永久删除符合清理条件且未受保护的历史记录。默认关闭；请先扫描并保护重要记录。')
    form.addWidget(QLabel('录像方式'), 0, 0)
    form.addWidget(w.recording_mode, 0, 1)
    form.addWidget(QLabel('空间上限'), 0, 2)
    form.addWidget(w.storage_max_gb, 0, 3)
    form.addWidget(QLabel('保留天数'), 1, 0)
    form.addWidget(w.storage_days, 1, 1)
    form.addWidget(w.storage_automatic, 1, 2, 1, 2)
    w.storage_policy_body.hide()
    w.storage_policy_toggle.toggled.connect(w.storage_policy_body.setVisible)
    w.storage_policy_toggle.toggled.connect(lambda opened: w.storage_policy_toggle.setText('收起设置' if opened else '展开设置'))
    policy_layout.addWidget(w.storage_policy_body)
    layout.addWidget(policy)
    records = QFrame()
    records.setObjectName('panel')
    body = QVBoxLayout(records)
    body.setContentsMargins(18, 18, 18, 18)
    body.setSpacing(14)
    actions = QHBoxLayout()
    title = QLabel('已保存记录')
    title.setObjectName('sectionTitle')
    actions.addWidget(title, 1)
    help_button = QPushButton('存储说明')
    help_button.setObjectName('quiet')
    help_button.clicked.connect(lambda: QMessageBox.information(w, '存储说明',
        '这里管理本软件生成的录像、截图、检测记录和核查意见。\n\n'
        '点击“扫描记录”可查看占用与清理预览。“清理记录”需要再次确认。\n'
        '标记为重要或正在使用的记录会受到保护。\n\n'
        '事件录像最多保留确认前5秒、后10秒，缓冲不足时前段可能较短。'
        '本地视频分析保存完整的处理录像。\n\n'
        '源视频、模型和已导出的文件不在这里清理。自动清理默认关闭。'))
    actions.addWidget(help_button)
    w.storage_scan = QPushButton('扫描记录')
    w.storage_scan.setObjectName('primary')
    w.storage_scan.clicked.connect(w.scan_storage)
    actions.addWidget(w.storage_scan)
    w.storage_cleanup = QPushButton('清理记录')
    w.storage_cleanup.setObjectName('stop')
    w.storage_cleanup.clicked.connect(w.clean_storage)
    actions.addWidget(w.storage_cleanup)
    body.addLayout(actions)
    w.storage_status = QLabel('点击扫描，查看记录占用')
    w.storage_status.setWordWrap(True)
    w.storage_status.setObjectName('muted')
    body.addWidget(w.storage_status)
    w.storage_table = table(['记录名称', '占用空间', '保留状态', '清理计划'])
    w.storage_table.itemSelectionChanged.connect(w._storage_selection_changed)
    body.addWidget(w.storage_table, 1)
    selected = QHBoxLayout()
    w.storage_protect = QPushButton('标记为重要')
    w.storage_protect.clicked.connect(w.toggle_storage_protection)
    w.storage_release = QPushButton('结束当前查看')
    w.storage_release.clicked.connect(w.release_current_record)
    selected.addWidget(w.storage_protect)
    selected.addWidget(w.storage_release)
    selected.addStretch()
    body.addLayout(selected)
    layout.addWidget(records, 1)
    w.storage_tab_index = w.tabs.addTab(page, '存储管理')
